use lapis_app_protocol::{content::*, operations::*};
use ts_rs::{Config, TS};

pub fn declarations(config: &Config) -> Vec<String> {
    vec![
        OperationArgument::decl(config),
        OperationHelp::decl(config),
        OperationDescriptor::decl(config),
        OperationCatalog::decl(config),
        OperationRequest::decl(config),
        OperationOutcome::decl(config),
        OperationReply::decl(config),
        OperationContribution::decl(config),
    ]
}

pub fn typescript(config: &Config) -> String {
    let mut types = vec![
        ContentEffect::decl(config),
        ContentErrorCode::decl(config),
        ContentEffectStatus::decl(config),
        ContentError::decl(config),
    ];
    types.extend(declarations(config));
    format!(
        "// Generated by lapis-app-protocol export. Do not edit.\nexport const OPERATION_PROTOCOL_MAJOR = 1 as const;\n{}\n",
        types
            .iter()
            .map(|s| format!("export {s}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
